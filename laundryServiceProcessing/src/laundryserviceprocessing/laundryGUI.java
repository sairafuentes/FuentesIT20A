private void removeOrder(String transactionID) {

    laundryQueue temporaryQueue =
        new laundryQueue(100);

    while (!queue.isEmpty()) {

        laundryOrder order = queue.dequeue();

        if (!order.getTransactionID()
                .equalsIgnoreCase(transactionID)) {

            temporaryQueue.enqueue(order);
        }
    }

    queue = temporaryQueue;
}

    
private void refreshTable() {

    model.setRowCount(0);

    for (int i = 0; i < queue.getCount(); i++) {

        laundryOrder order = queue.getOrderAt(i);

        model.addRow(new Object[] {
            order.getTransactionID(),
            order.getCustomerName(),
            order.getWeight(),
            order.getServiceType(),
            order.getStatus()
        });
    }
}


