order.setStatus("Completed");

refreshTable();

javax.swing.JOptionPane.showMessageDialog(
    this,
    "Order processed successfully!\n\n" +
    "Transaction ID: " + order.getTransactionID() +
    "\nCustomer: " + order.getCustomerName());
